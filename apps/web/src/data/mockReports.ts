export function getReportById(id: string) {
  return mockReports.find((report) => report.id === id);
}

export function getRelatedReports(report: Report, limit = 3) {
  return mockReports
    .filter((candidate) => candidate.id !== report.id)
    .sort((a, b) => {
      const sameRegionA = a.region === report.region ? 0 : 1;
      const sameRegionB = b.region === report.region ? 0 : 1;
      return sameRegionA - sameRegionB;
    })
    .slice(0, limit);
}
